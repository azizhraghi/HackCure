// Bundles twin-src/main.js (three.js) + the glb model into a self-contained HTML string
// for the WebView: src/components/twin/twinHtml.ts
// Run: npm run build:twin
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const result = await build({
  entryPoints: [resolve(root, 'twin-src/main.js')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2019',
  write: false,
});

const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const glb = readFileSync(resolve(root, 'assets/twin/body.glb')).toString('base64');

const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<style>html{color-scheme:only light}html,body{margin:0;height:100%;overflow:hidden;background:radial-gradient(ellipse at 50% 40%,#0f3550,#071a2b 54%,#02060c);touch-action:none}canvas{display:block}</style>
</head><body><script>window.__GLB=${JSON.stringify(glb)};</script><script>${js}</script></body></html>`;

writeFileSync(
  resolve(root, 'src/components/twin/twinHtml.ts'),
  `// AUTO-GENERATED by scripts/build-twin.mjs — do not edit.\n/* eslint-disable */\nexport default ${JSON.stringify(html)};\n`,
);
console.log(`twinHtml.ts written (${(html.length / 1024).toFixed(0)} KB)`);
